#!/usr/bin/env bash
# Собирает docs/ для MkDocs из корня репозитория: README → главная страница,
# уроки (NN-*) и final-project — как есть. Навигация строится из дерева
# автоматически (mkdocs.yml), поэтому новый урок публикуется без правки конфига.
set -euo pipefail
cd "$(dirname "$0")/.."

rm -rf docs
mkdir docs
cp README.md docs/index.md

for d in [0-9][0-9]-*/ final-project/ kurs/; do
  cp -R "$d" "docs/$d"
done

# Рабочее окружение и кэши в git не лежат, поэтому в CI их нет — но при
# локальной сборке они копируются вместе с деревом, и docs/ разрастается до
# гигабайтов. Удаляем после копирования: rsync с исключениями был бы короче,
# но его нет в образе CI (python:3.12-slim), а ставить ради этого пакет дорого.
find docs \( -name '.venv' -o -name '__pycache__' -o -name '.pytest_cache' \
           -o -name 'node_modules' \) -prune -exec rm -rf {} +

# Оригинальные PDF лекций на сайт не идут. Две причины, и обе достаточные.
#
# 1. Лицензия. README репозитория прямо запрещает публиковать защищённый
#    авторским правом контент OTUS — оригинальные презентации преподавателей.
#    Pages внутренний, но это всё равно публикация.
# 2. Размер. Тридцать три файла дают 106 МБ из 136, и артефакт сборки
#    перестал приниматься: «413 Request Entity Too Large», сайт не
#    обновлялся вовсе. После чистки остаётся 30 МБ.
#
# Сами файлы остаются в репозитории и открываются из него. Ссылки на них из
# конспектов в пределах сайта не резолвятся — это допущено настройкой
# validation в mkdocs.yml, иначе --strict валил бы сборку.
find docs -path 'docs/[0-9][0-9]-*/artifacts/*' -iname '*.pdf' -delete

# Лендинг защиты — обычный html рядом с сайтом: mkdocs копирует не-md как есть,
# и страница доступна по /landing/. Отдельной сборки не требует.
cp -R landing docs/landing
