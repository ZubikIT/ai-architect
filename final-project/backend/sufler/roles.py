"""Конфигурация «цифровых сотрудников» и детерминированная маршрутизация (ADR-0015).

Роль — это три вещи вместе: **промпт** (компетенция), **инструменты** и **права**.
Права здесь объявляются не как «что агент видит», а как «какими ролями субъекта
агент вправе воспользоваться»: фактический доступ всегда есть пересечение прав
пользователя с этим списком (ADR-0016 + least privilege, ASI03). Кадровик не
получает юридический контур, даже если пользователь его имеет.

Маршрутизация — правилами. Целью агента нельзя манипулировать текстом, если цель
выбрана не текстом (ADR-0015, правило 1): LLM-классификация остаётся запасным
путём для запросов, не попавших ни в одно правило.

Добавление «сотрудника» — это запись в `ROLES`, а не правка графа выполнения.
"""
from dataclasses import dataclass

from .access import PUBLIC


@dataclass(frozen=True)
class AgentRole:
    id: str
    title: str            # как «сотрудник» представляется пользователю
    mission: str          # системный промпт: компетенция и границы
    grants: tuple         # роли субъекта, которыми агент вправе воспользоваться
    keywords: tuple       # правила маршрутизации супервизора
    max_tool_calls: int = 2

    def effective_roles(self, subject_roles) -> tuple:
        """Права агента = права пользователя ∩ мандат роли (никогда не шире)."""
        eff = tuple(r for r in subject_roles if r in self.grants)
        return eff or (PUBLIC,)   # без пересечения остаётся только общедоступное


