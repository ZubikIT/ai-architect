def score_roles(question: str) -> dict:
    """Сколько правил каждой роли сработало на вопросе."""
    low = question.lower()
    return {r.id: sum(1 for k in r.keywords if k in low) for r in ROLES}


def route_by_rules(question: str, fanout: int = 2) -> dict:
    """Детерминированная маршрутизация: кому из «сотрудников» адресован вопрос.

    Возвращает решение вместе с обоснованием — оно уходит в ReAct-trace и в аудит,
    чтобы ошибку маршрутизации можно было увидеть, а не угадывать.

    При низкой уверенности запрос уходит веером двум ролям: цена — лишний хоп,
    выигрыш — вопрос на стыке компетенций (командировка + ПДн) не теряет половину
    ответа из-за того, что супервизор выбрал одну сторону (ADR-0015, митигация
    риска ошибки маршрутизации).
    """
    scores = score_roles(question)
    hits = sorted(((v, k) for k, v in scores.items() if v), reverse=True)
    if not hits:
        return {"mode": "none", "route": [], "scores": scores, "confidence": 0.0}

    total = sum(v for v, _ in hits)
    top, best = hits[0][0], [hits[0][1]]
    confidence = top / total
    if len(hits) > 1 and confidence < 0.6 and fanout > 1:
        best = [k for _, k in hits[:fanout]]
    return {"mode": "rules", "route": best, "scores": scores,
            "confidence": round(confidence, 2)}


